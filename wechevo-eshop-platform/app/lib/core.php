/* Core: config, database, request helpers, routing, views. No external dependencies. */

final class Config
{
    private static array $c = [];

    public static function load(): void
    {
        $file = DATA . '/config.php';
        self::$c = is_file($file) ? (require $file) : [];
    }

    public static function get(string $k, $default = null)
    {
        return self::$c[$k] ?? $default;
    }

    public static function installed(): bool
    {
        return !empty(self::$c['app_key']);
    }

    /** Written once by the setup wizard. Holds only machine values, never business limits. */
    public static function write(array $values): void
    {
        self::$c = array_merge(self::$c, $values);
        $php = "<?php\n// Generated by the setup wizard. Keep private.\nreturn " . var_export(self::$c, true) . ";\n";
        file_put_contents(DATA . '/config.php', $php, LOCK_EX);
        @chmod(DATA . '/config.php', 0600);
    }
}

final class DB
{
    private static ?PDO $platform = null;
    private static array $shops = [];

    public static function platform(): PDO
    {
        if (!self::$platform) {
            self::$platform = self::open(DATA . '/platform.sqlite', 'platform');
        }
        return self::$platform;
    }

    public static function shopPath(int $shopId): string
    {
        return DATA . '/shops/' . $shopId . '.sqlite';
    }

    /** Each tenant has its own database file: isolation by construction. */
    public static function shop(int $shopId): PDO
    {
        if ($shopId <= 0) {
            throw new RuntimeException('Invalid shop id');
        }
        if (!isset(self::$shops[$shopId])) {
            if (!is_dir(DATA . '/shops')) {
                mkdir(DATA . '/shops', 0775, true);
            }
            self::$shops[$shopId] = self::open(self::shopPath($shopId), 'shop');
        }
        return self::$shops[$shopId];
    }

    public static function forget(int $shopId): void
    {
        unset(self::$shops[$shopId]);
    }

    private static function open(string $file, string $schema): PDO
    {
        $pdo = new PDO('sqlite:' . $file, null, null, [
            PDO::ATTR_ERRMODE => PDO::ERRMODE_EXCEPTION,
            PDO::ATTR_DEFAULT_FETCH_MODE => PDO::FETCH_ASSOC,
        ]);
        $pdo->exec('PRAGMA journal_mode=WAL; PRAGMA foreign_keys=ON; PRAGMA busy_timeout=8000; PRAGMA synchronous=NORMAL;');
        // accent/case-insensitive Greek matching inside SQL: WHERE fold(name) LIKE ?
        if (method_exists($pdo, 'createFunction')) {
            $pdo->createFunction('fold', fn($s) => fold((string)$s), 1, PDO::SQLITE_DETERMINISTIC);
        } else {
            $pdo->sqliteCreateFunction('fold', fn($s) => fold((string)$s), 1, PDO::SQLITE_DETERMINISTIC);
        }
        self::migrate($pdo, $schema);
        return $pdo;
    }

    private static function migrate(PDO $pdo, string $schema): void
    {
        $current = (int)$pdo->query('PRAGMA user_version')->fetchColumn();
        $migrations = require APP . '/migrations/' . $schema . '.php';
        foreach ($migrations as $version => $sql) {
            if ($version > $current) {
                $pdo->beginTransaction();
                try {
                    $pdo->exec($sql);
                    $pdo->exec('PRAGMA user_version=' . (int)$version);
                    $pdo->commit();
                } catch (Throwable $e) {
                    $pdo->rollBack();
                    throw $e;
                }
            }
        }
    }
}

/* ---------- small query helpers ---------- */
function q(PDO $db, string $sql, array $p = []): PDOStatement
{
    $st = $db->prepare($sql);
    // bind with real types: SQLite compares INTEGER 0 and TEXT '0' as different values
    $named = $p && !array_is_list($p) && !array_filter(array_keys($p), fn($k) => !is_string($k) || !preg_match('/^:?[a-z_]\w*$/i', $k));
    if (!$named) {
        $p = array_values($p);
    }
    $i = 0;
    foreach ($p as $k => $v) {
        $key = is_int($k) ? ++$i : (str_starts_with($k, ':') ? $k : ':' . $k);
        $st->bindValue($key, $v, match (true) {
            is_int($v), is_bool($v) => PDO::PARAM_INT,
            $v === null => PDO::PARAM_NULL,
            default => PDO::PARAM_STR,
        });
    }
    $st->execute();
    return $st;
}
function row(PDO $db, string $sql, array $p = []): ?array
{
    $r = q($db, $sql, $p)->fetch();
    return $r === false ? null : $r;
}
function rows(PDO $db, string $sql, array $p = []): array
{
    return q($db, $sql, $p)->fetchAll();
}
function val(PDO $db, string $sql, array $p = [])
{
    $v = q($db, $sql, $p)->fetchColumn();
    return $v === false ? null : $v;
}
function insert(PDO $db, string $table, array $data): int
{
    $cols = array_keys($data);
    $sql = 'INSERT INTO ' . $table . ' (' . implode(',', $cols) . ') VALUES (' . implode(',', array_fill(0, count($cols), '?')) . ')';
    q($db, $sql, array_values($data));
    return (int)$db->lastInsertId();
}
function update(PDO $db, string $table, array $data, string $where, array $wp = []): int
{
    $set = implode(',', array_map(fn($c) => "$c = ?", array_keys($data)));
    return q($db, "UPDATE $table SET $set WHERE $where", array_merge(array_values($data), $wp))->rowCount();
}

/* ---------- settings (key/value with JSON) ---------- */
function setting_get(PDO $db, string $key, $default = null)
{
    $v = val($db, 'SELECT value FROM settings WHERE key = ?', [$key]);
    if ($v === null) {
        return $default;
    }
    $d = json_decode($v, true);
    return json_last_error() === JSON_ERROR_NONE ? $d : $v;
}
function setting_set(PDO $db, string $key, $value): void
{
    q($db, 'INSERT INTO settings(key, value) VALUES(?, ?) ON CONFLICT(key) DO UPDATE SET value = excluded.value', [$key, json_encode($value, JSON_UNESCAPED_UNICODE)]);
}

/* ---------- formatting ---------- */
function e($s): string
{
    return htmlspecialchars((string)$s, ENT_QUOTES | ENT_SUBSTITUTE, 'UTF-8');
}
function now(): string
{
    return gmdate('Y-m-d H:i:s');
}
function money($n, string $cur = 'EUR'): string
{
    return number_format((float)$n, 2, ',', '.') . ' €';
}
function dt(?string $utc, string $fmt = 'd/m/Y H:i'): string
{
    if (!$utc) {
        return '—';
    }
    $d = new DateTime($utc, new DateTimeZone('UTC'));
    $d->setTimezone(new DateTimeZone('Europe/Athens'));
    return $d->format($fmt);
}
function d(?string $utc): string
{
    return dt($utc, 'd/m/Y');
}
function slugify(string $s): string
{
    static $map = [
        'α'=>'a','ά'=>'a','β'=>'v','γ'=>'g','δ'=>'d','ε'=>'e','έ'=>'e','ζ'=>'z','η'=>'i','ή'=>'i','θ'=>'th',
        'ι'=>'i','ί'=>'i','ϊ'=>'i','ΐ'=>'i','κ'=>'k','λ'=>'l','μ'=>'m','ν'=>'n','ξ'=>'x','ο'=>'o','ό'=>'o',
        'π'=>'p','ρ'=>'r','σ'=>'s','ς'=>'s','τ'=>'t','υ'=>'y','ύ'=>'y','ϋ'=>'y','ΰ'=>'y','φ'=>'f','χ'=>'ch',
        'ψ'=>'ps','ω'=>'o','ώ'=>'o',
    ];
    $s = mb_strtolower(trim($s), 'UTF-8');
    $s = strtr($s, ['ου' => 'ou', 'ού' => 'ou', 'αι' => 'ai', 'ει' => 'ei', 'οι' => 'oi']);
    $s = strtr($s, $map);
    if (function_exists('transliterator_transliterate')) {
        $s = transliterator_transliterate('Any-Latin; Latin-ASCII', $s);
    }
    $s = preg_replace('/[^a-z0-9]+/', '-', strtolower($s));
    $s = trim($s, '-');
    return $s !== '' ? substr($s, 0, 90) : 'item';
}
/** Accent- and case-insensitive key for Greek search/comparison. */
function fold(string $s): string
{
    $s = mb_strtolower($s, 'UTF-8');
    if (class_exists('Normalizer')) {
        $s = Normalizer::normalize($s, Normalizer::FORM_D);
        $s = preg_replace('/\p{Mn}+/u', '', $s);
    }
    return str_replace('ς', 'σ', $s);
}
function random_token(int $bytes = 24): string
{
    return rtrim(strtr(base64_encode(random_bytes($bytes)), '+/', '-_'), '=');
}
function to_float($v): ?float
{
    if ($v === null || $v === '') {
        return null;
    }
    $v = str_replace([' ', '€'], '', (string)$v);
    if (preg_match('/^-?\d{1,3}(\.\d{3})+(,\d+)?$/', $v)) {
        $v = str_replace('.', '', $v);
    }
    $v = str_replace(',', '.', $v);
    return is_numeric($v) ? (float)$v : null;
}

/* ---------- request ---------- */
function req_host(): string
{
    $h = strtolower($_SERVER['HTTP_HOST'] ?? 'localhost');
    $h = preg_replace('/:\d+$/', '', $h);
    return preg_replace('/[^a-z0-9.\-]/', '', $h);
}
function req_port_suffix(): string
{
    $h = $_SERVER['HTTP_HOST'] ?? '';
    return preg_match('/(:\d+)$/', $h, $m) ? $m[1] : '';
}
function is_https(): bool
{
    return (!empty($_SERVER['HTTPS']) && $_SERVER['HTTPS'] !== 'off')
        || (($_SERVER['HTTP_X_FORWARDED_PROTO'] ?? '') === 'https')
        || (($_SERVER['SERVER_PORT'] ?? '') == 443);
}
function req_path(): string
{
    $p = parse_url($_SERVER['REQUEST_URI'] ?? '/', PHP_URL_PATH) ?: '/';
    $p = rawurldecode($p);
    return '/' . ltrim(preg_replace('#/+#', '/', $p), '/');
}
function is_post(): bool
{
    return ($_SERVER['REQUEST_METHOD'] ?? 'GET') === 'POST';
}
function input(string $k, $default = '')
{
    $v = $_POST[$k] ?? $_GET[$k] ?? $default;
    return is_string($v) ? trim($v) : $v;
}
function client_ip(): string
{
    return substr((string)($_SERVER['REMOTE_ADDR'] ?? '0.0.0.0'), 0, 45);
}
function base_url(): string
{
    return (is_https() ? 'https://' : 'http://') . ($_SERVER['HTTP_HOST'] ?? 'localhost');
}
function redirect(string $to, int $code = 302): never
{
    header('Location: ' . $to, true, $code);
    exit;
}
function json_out($data, int $code = 200): never
{
    http_response_code($code);
    header('Content-Type: application/json; charset=utf-8');
    echo json_encode($data, JSON_UNESCAPED_UNICODE);
    exit;
}


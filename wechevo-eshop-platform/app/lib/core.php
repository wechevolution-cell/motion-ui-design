function pager(int $total, int $page, int $per, string $base): string
{
    $pages = (int)ceil($total / max(1, $per));
    if ($pages <= 1) {
        return '';
    }
    $sep = str_contains($base, '?') ? '&' : '?';
    $h = '<nav class="pager" aria-label="Σελίδες">';
    $show = array_unique(array_filter([1, $page - 2, $page - 1, $page, $page + 1, $page + 2, $pages], fn($p) => $p >= 1 && $p <= $pages));
    sort($show);
    $prev = 0;
    foreach ($show as $p) {
        if ($prev && $p > $prev + 1) {
            $h .= '<span aria-hidden="true">…</span>';
        }
        $h .= $p === $page ? '<span class="cur" aria-current="page">' . $p . '</span>' : '<a href="' . e($base . $sep . 'page=' . $p) . '">' . $p . '</a>';
        $prev = $p;
    }
    return $h . '</nav>';
}

function quota_bar(int $active, int $limit, string $label = 'ΕΝΕΡΓΑ ΠΡΟΪΟΝΤΑ'): string
{
    $pct = $limit > 0 ? min(100, (int)round($active / $limit * 100)) : 100;
    $cls = $active >= $limit ? 'full' : ($pct >= 85 ? 'near' : '');
    return '<div class="quota ' . $cls . '"><div class="spread"><strong>' . e($label) . ': <span class="num">' . $active . ' / ' . $limit . '</span></strong><span class="muted">' . max(0, $limit - $active) . ' διαθέσιμες θέσεις</span></div>'
        . '<div class="bar" role="progressbar" aria-valuemin="0" aria-valuemax="' . $limit . '" aria-valuenow="' . $active . '" aria-label="' . e($label) . '"><i style="width:' . $pct . '%"></i></div></div>';
}

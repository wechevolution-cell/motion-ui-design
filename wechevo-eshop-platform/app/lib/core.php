/* ---------- routing ---------- */
final class Router
{
    private array $routes = [];

    public function add(string $methods, string $pattern, callable $handler): void
    {
        $this->routes[] = [explode('|', $methods), '#^' . $pattern . '$#u', $handler];
    }

    public function dispatch(string $path): void
    {
        $method = $_SERVER['REQUEST_METHOD'] ?? 'GET';
        $allowed = false;
        foreach ($this->routes as [$methods, $re, $h]) {
            if (preg_match($re, $path, $m)) {
                if (!in_array($method, $methods, true) && !($method === 'HEAD' && in_array('GET', $methods, true))) {
                    $allowed = true;
                    continue;
                }
                $args = array_values(array_filter($m, 'is_string', ARRAY_FILTER_USE_KEY));
                $h(...$args);
                return;
            }
        }
        abort($allowed ? 405 : 404);
    }
}

/* ---------- views ---------- */
function render(string $file, array $vars = []): string
{
    extract($vars, EXTR_SKIP);
    ob_start();
    try {
        require $file;
    } catch (Throwable $t) {
        ob_end_clean();
        throw $t;
    }
    return ob_get_clean();
}

